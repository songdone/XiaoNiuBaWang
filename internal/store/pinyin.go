func gb2312Rank(r rune) (uint16, bool) {
	if r < 0x4E00 || r > 0x9FA5 {
		return 0, false
	}
	target := uint32(r) << 16
	i := sort.Search(len(gb2312L1), func(i int) bool { return gb2312L1[i] >= target })
	if i < len(gb2312L1) && gb2312L1[i]>>16 == uint32(r) {
		return uint16(gb2312L1[i] & 0xFFFF), true
	}
	return 0, false
}

// titleSortKey produces a deterministic BINARY-sortable key: ASCII/Latin
// folds via strings.ToLower while GB2312 Level-1 Hanzi map to Pinyin order.
func titleSortKey(s string) string {
	hasCJK := false
	for _, r := range s {
		if r >= 0x4E00 && r <= 0x9FA5 {
			hasCJK = true
			break
		}
	}
	if !hasCJK {
		return strings.ToLower(s)
	}
	var b strings.Builder
	b.Grow(len(s) * 2)
	for _, r := range s {
		if rank, ok := gb2312Rank(r); ok {
			b.WriteRune(rune(0xE000 + int(rank)))
			continue
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}
